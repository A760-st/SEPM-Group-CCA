-- =====================================================================
-- College Event Management System (SEPM Mini-Project)
-- PostgreSQL DDL Script  --  consistent with System Architecture v1.1
--                            and the five-entity ER diagram
--
-- Tables : users, venues, events, registrations, certificates
-- Target : PostgreSQL 13 or later
-- Run    : psql -U <user> -d <database> -f SEPM_Database_Schema.sql
--
-- Naming conventions
--   tables           : lower-case plural snake_case      (users)
--   columns          : lower-case snake_case             (student_id_number)
--   primary keys     : pk_<table>
--   foreign keys     : fk_<table>_<meaning>
--   unique           : uq_<table>_<column(s)>
--   check            : chk_<table>_<rule>
--   indexes          : idx_<table>_<column(s)>
--   enum types       : singular snake_case               (user_role)
--
-- No sample data is inserted in this script.
-- =====================================================================


-- ---------------------------------------------------------------------
-- PART 1: ENUM TYPES
-- Native PostgreSQL enums reject any value outside the permitted list,
-- which gives the same protection as a CHECK (col IN (...)) constraint
-- and maps directly to Prisma enums.
-- ---------------------------------------------------------------------

CREATE TYPE user_role AS ENUM ('STUDENT', 'ORGANIZER', 'ADMIN');

CREATE TYPE event_status AS ENUM ('DRAFT', 'PUBLISHED', 'CANCELLED', 'COMPLETED');

CREATE TYPE registration_status AS ENUM ('REGISTERED', 'CANCELLED');


-- ---------------------------------------------------------------------
-- PART 2: TABLES
-- Created in foreign-key dependency order:
--   users, venues  ->  events  ->  registrations  ->  certificates
-- ---------------------------------------------------------------------

-- TABLE 1: USERS -------------------------------------------------------
CREATE TABLE users (
    id                 INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    name               VARCHAR(100)  NOT NULL,
    email              VARCHAR(255)  NOT NULL,
    student_id_number  VARCHAR(30)   NOT NULL,
    password_hash      VARCHAR(255)  NOT NULL,
    role               user_role     NOT NULL DEFAULT 'STUDENT',
    department         VARCHAR(100),
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT pk_users                    PRIMARY KEY (id),
    CONSTRAINT uq_users_email              UNIQUE (email),
    CONSTRAINT uq_users_student_id_number  UNIQUE (student_id_number),
    -- Keeps e-mail comparison case-insensitive in practice: the backend
    -- stores e-mails in lower case and the database refuses anything else.
    CONSTRAINT chk_users_email_lowercase   CHECK (email = lower(email))
);

-- TABLE 2: VENUES ------------------------------------------------------
CREATE TABLE venues (
    id        INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    name      VARCHAR(100)  NOT NULL,
    location  VARCHAR(255)  NOT NULL,
    capacity  INTEGER       NOT NULL,

    CONSTRAINT pk_venues                   PRIMARY KEY (id),
    CONSTRAINT uq_venues_name              UNIQUE (name),
    CONSTRAINT chk_venues_capacity_positive CHECK (capacity > 0)
);

-- TABLE 3: EVENTS ------------------------------------------------------
CREATE TABLE events (
    id                     INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    title                  VARCHAR(200)  NOT NULL,
    description            TEXT          NOT NULL,
    organizer_id           INTEGER       NOT NULL,
    venue_id               INTEGER       NOT NULL,
    start_time             TIMESTAMPTZ   NOT NULL,
    end_time               TIMESTAMPTZ   NOT NULL,
    registration_deadline  TIMESTAMPTZ   NOT NULL,
    max_participants       INTEGER,                      -- NULL = no limit
    status                 event_status  NOT NULL DEFAULT 'DRAFT',
    cancel_reason          TEXT,                         -- NULL unless cancelled
    created_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at             TIMESTAMPTZ   NOT NULL DEFAULT now(),

    CONSTRAINT pk_events PRIMARY KEY (id),

    CONSTRAINT fk_events_organizer
        FOREIGN KEY (organizer_id) REFERENCES users (id)
        ON DELETE RESTRICT ON UPDATE CASCADE,

    CONSTRAINT fk_events_venue
        FOREIGN KEY (venue_id) REFERENCES venues (id)
        ON DELETE RESTRICT ON UPDATE CASCADE,

    CONSTRAINT chk_events_end_after_start
        CHECK (end_time > start_time),

    CONSTRAINT chk_events_max_participants_positive
        CHECK (max_participants IS NULL OR max_participants > 0)
);

-- TABLE 4: REGISTRATIONS -----------------------------------------------
CREATE TABLE registrations (
    id                   INTEGER              GENERATED BY DEFAULT AS IDENTITY,
    event_id             INTEGER              NOT NULL,
    student_id           INTEGER              NOT NULL,
    status               registration_status  NOT NULL DEFAULT 'REGISTERED',
    certificate_eligible BOOLEAN              NOT NULL DEFAULT false,
    registered_at        TIMESTAMPTZ          NOT NULL DEFAULT now(),

    CONSTRAINT pk_registrations PRIMARY KEY (id),

    CONSTRAINT fk_registrations_event
        FOREIGN KEY (event_id) REFERENCES events (id)
        ON DELETE RESTRICT ON UPDATE CASCADE,

    CONSTRAINT fk_registrations_student
        FOREIGN KEY (student_id) REFERENCES users (id)
        ON DELETE RESTRICT ON UPDATE CASCADE,

    -- A student can register only once for the same event.
    CONSTRAINT uq_registrations_event_student UNIQUE (event_id, student_id)
);

-- TABLE 5: CERTIFICATES ------------------------------------------------
CREATE TABLE certificates (
    id               INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    registration_id  INTEGER       NOT NULL,
    certificate_no   VARCHAR(50)   NOT NULL,
    file_path        VARCHAR(500)  NOT NULL,
    issued_at        TIMESTAMPTZ   NOT NULL DEFAULT now(),
    issued_by        INTEGER       NOT NULL,

    CONSTRAINT pk_certificates PRIMARY KEY (id),

    -- UNIQUE on the foreign key makes REGISTRATIONS-CERTIFICATES
    -- a one-to-zero-or-one relationship.
    CONSTRAINT uq_certificates_registration_id UNIQUE (registration_id),
    CONSTRAINT uq_certificates_certificate_no  UNIQUE (certificate_no),

    CONSTRAINT fk_certificates_registration
        FOREIGN KEY (registration_id) REFERENCES registrations (id)
        ON DELETE RESTRICT ON UPDATE CASCADE,

    CONSTRAINT fk_certificates_issuer
        FOREIGN KEY (issued_by) REFERENCES users (id)
        ON DELETE RESTRICT ON UPDATE CASCADE
);


-- ---------------------------------------------------------------------
-- PART 3: INDEXES
-- Only indexes that are NOT already provided by a PRIMARY KEY or UNIQUE
-- constraint are created here.
--
-- Already indexed automatically by constraints:
--   users.email, users.student_id_number, venues.name,
--   registrations(event_id, student_id)  (also serves event_id lookups),
--   certificates.registration_id, certificates.certificate_no
-- ---------------------------------------------------------------------

-- Organizer dashboard: "events organized by this user"; also speeds up FK checks.
CREATE INDEX idx_events_organizer_id
    ON events (organizer_id);

-- Venue clash check and "events at this venue"; also speeds up FK checks.
CREATE INDEX idx_events_venue_id_start_time
    ON events (venue_id, start_time);

-- Public event list: WHERE status = 'PUBLISHED' ORDER BY start_time.
CREATE INDEX idx_events_status_start_time
    ON events (status, start_time);

-- "My registrations" for a student; also speeds up FK checks.
CREATE INDEX idx_registrations_student_id
    ON registrations (student_id);


-- ---------------------------------------------------------------------
-- PART 4: AUTOMATIC updated_at MAINTENANCE (events)
-- Keeps events.updated_at correct even for updates made outside Prisma.
-- ---------------------------------------------------------------------

CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS trigger AS $$
BEGIN
    NEW.updated_at = now();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_events_set_updated_at
    BEFORE UPDATE ON events
    FOR EACH ROW
    EXECUTE FUNCTION set_updated_at();


